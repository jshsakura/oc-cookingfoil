const wordsFor = (lang) => RETRO_MESSAGES[lang] ?? RETRO_MESSAGES.en;

/** The message `key` in `lang` (English when it is not an admin language), placeholders filled. Pure. */
export function retroText(lang, key, vars = {}) {
  const text = wordsFor(lang)[key] ?? RETRO_MESSAGES.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
}

/** Whether `code` names a message here. Pure. */
export const isRetroCode = (code) => typeof code === "string" && Object.hasOwn(RETRO_MESSAGES.en, code);

/** The message `key` in the request's language. */
export const retroWord = (req, key, vars = {}) => retroText(requestLang(req), key, vars);

/** A stored { code, vars } (a group's reason) in `lang`; a plain string is passed on as it is. Pure. */
export function retroSaid(lang, said) {
  if (!said || typeof said !== "object") return said ?? "";
  const vars = Object.fromEntries(Object.entries(said.vars ?? {}).map(([k, v]) => [k, isRetroCode(v) ? retroText(lang, v) : v]));
  return retroText(lang, said.code, vars);
}

/** An error that says one of the messages here: English message, `code` and `vars`. */
export class RetroError extends Error {
  static of(code, vars = {}, status = 400) {
    return Object.assign(new RetroError(retroText("en", code, vars)), { code, vars, status });
  }
}

/** A route's JSON error: the text in the request's language, and its code when it has one. */
export const retroError = (req, err) => (isRetroCode(err?.code)
  ? { error: retroText(requestLang(req), err.code, err.vars), code: err.code }
  : { error: String(err?.message ?? err) });


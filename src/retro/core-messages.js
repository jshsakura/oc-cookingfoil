const wordsFor = (lang) => CORE_MESSAGES[lang] ?? (lang === "zh-Hant" ? CORE_MESSAGES.zh : CORE_MESSAGES.en);

/** The message `key` in `lang` (English when it is not an admin language), placeholders filled. Pure. */
export function coreText(lang, key, vars = {}) {
  const text = wordsFor(lang)[key] ?? CORE_MESSAGES.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
}

/** The Korean text the pack's errors carry. Pure. */
export const coreKo = (key, vars) => coreText("ko", key, vars);

const wordsFor = (lang) => CORE_MESSAGES[lang] ?? CORE_MESSAGES.en;

/** The message `key` in `lang` (English when it is not an admin language), placeholders filled. Pure. */
export function coreText(lang, key, vars = {}) {
  const text = wordsFor(lang)[key] ?? CORE_MESSAGES.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
}

/** Whether `code` names a message here. Pure. */
export const isCoreCode = (code) => typeof code === "string" && Object.hasOwn(CORE_MESSAGES.en, code);

/** The message `key` in the request's language. */
export const coreWord = (req, key, vars = {}) => coreText(requestLang(req), key, vars);

/** What a thrown or stored failure ({ message, code?, vars? }) says in `lang`: by its code, else its message as it is. Pure. */
export const coreErrorText = (lang, err) => (isCoreCode(err?.code) ? coreText(lang, err.code, err.vars) : String(err?.message ?? err));

/** A route's JSON error for a core or pack failure: the text in the request's language, and its code when it has one. */
export const coreError = (req, err) => ({ error: coreErrorText(requestLang(req), err), ...(isCoreCode(err?.code) ? { code: err.code } : {}) });


/**
 * Routes that have no capability, and why. src/capabilities/registry.js is the other half: the
 * coverage test (test/unit/capability-coverage.test.js) fails on any route that is in neither.
 *
 * OPT_OUT is for routes an agent should never get as a tool. Each needs one of OPT_OUT_REASONS,
 * and adding one means raising OPT_OUT_CEILING in the coverage test in the same change.
 *
 * LEGACY_UNREGISTERED is every route that predates the registry. It only shrinks: when a capability
 * claims a route, delete its line here and lower LEGACY_CEILING in the coverage test. Never add to it.
 */

export const OPT_OUT_REASONS = {
  "browser-only": "a page, its assets, or a sign-in step a person does in the browser",
  "token-blocked": "accounts, sign-in, devices or binaries; automation tokens may never do it",
  "catalog-export": "bulk authenticated catalog export; interactive game queries are provided by capabilities",
  "binary-upload": "takes a file upload, which a tool call cannot carry",
  "mcp-transport": "the MCP endpoint itself, through which the capabilities are served as tools",
  "console-ui": "the console client's own interface data, read by the client and of no use as a tool",
  "legacy-unregistered": "predates the registry; only LEGACY_UNREGISTERED may use it",
};


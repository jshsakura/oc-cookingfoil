const wordsFor = (lang) => TRASH_MESSAGES[lang] ?? (lang === "zh-Hant" ? TRASH_MESSAGES.zh : TRASH_MESSAGES.en);

/** The message `key` in `lang` (English when it is not an admin language), placeholders filled. Pure. */
export function trashText(lang, key, vars = {}) {
  const text = wordsFor(lang)[key] ?? TRASH_MESSAGES.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
}

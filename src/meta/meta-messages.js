const wordsFor = (lang) => META_MESSAGES[lang] ?? META_MESSAGES.en;

/** The message `key` in `lang` (English when it is not an admin language), placeholders filled. Pure. */
export function metaText(lang, key, vars = {}) {
  const text = wordsFor(lang)[key] ?? META_MESSAGES.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => {
    const v = vars?.[name];
    if (v === undefined) return m;
    return String(typeof v === "function" ? v(lang) : v);
  });
}

/** Whether `code` names a message here. Pure. */
export const isMetaCode = (code) => typeof code === "string" && Object.hasOwn(META_MESSAGES.en, code);

/** The message key a failure carries: its `key` (where `code` is a public value), else its `code`. Pure. */
const keyOf = (err) => (isMetaCode(err?.key) ? err.key : isMetaCode(err?.code) ? err.code : null);

/** The message `key` in the request's language. */
export const metaWord = (req, key, vars = {}) => metaText(requestLang(req), key, vars);

/** What a thrown or stored failure ({ message, code?, vars? }) says in `lang`: by its key, else its message as it is. Pure. */
export const metaErrorText = (lang, err) => {
  const key = keyOf(err);
  return key ? metaText(lang, key, err.vars) : String(err?.message ?? err);
};

/** A route's JSON error for a meta failure: the text in the request's language, and its key as `code` when it has one. */
export const metaError = (req, err) => {
  const key = keyOf(err);
  return { error: metaErrorText(requestLang(req), err), ...(key ? { code: key } : {}) };
};

/** Sets `code` (or `key`) and `vars` on `err` and gives it the English message. Returns `err`. */
export function coded(err, key, vars = {}, { field = "code" } = {}) {
  err.message = metaText("en", key, vars);
  err[field] = key;
  err.vars = vars;
  return err;
}

